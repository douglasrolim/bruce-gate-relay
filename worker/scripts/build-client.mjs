// Bundles the browser client (client/*.ts + styles.css) and the icons into
// src/ui/generated/bundle.ts, so the Worker serves everything itself (no CDNs).
// Usage: node scripts/build-client.mjs [--check]   (--check fails if the bundle is over budget)

import { build, transform } from "esbuild";
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Budget for what goes over the wire (Cloudflare compresses text responses).
const BUDGET_BYTES = 50 * 1024;

const js = await build({
  entryPoints: [join(root, "client/main.ts")],
  bundle: true,
  minify: true,
  format: "esm",
  target: ["es2020", "safari15", "chrome100"],
  write: false,
  legalComments: "none",
});
const clientJs = js.outputFiles[0].text;

const css = await transform(await readFile(join(root, "client/styles.css"), "utf8"), {
  loader: "css",
  minify: true,
  target: ["safari15", "chrome100"],
});
const clientCss = css.code;

const iconSvg = (await readFile(join(root, "assets/icon.svg"), "utf8")).trim();
const pngs = {};
for (const name of ["icon-192", "icon-512", "icon-maskable-512", "apple-touch-icon"]) {
  pngs[name] = (await readFile(join(root, `assets/${name}.png`))).toString("base64");
}

const buildId = createHash("sha256").update(clientJs).update(clientCss).digest("hex").slice(0, 10);

const out = `// AUTO-GENERATED by scripts/build-client.mjs. Do not edit.
export const BUILD_ID = ${JSON.stringify(buildId)};
export const CLIENT_JS = ${JSON.stringify(clientJs)};
export const CLIENT_CSS = ${JSON.stringify(clientCss)};
export const APP_ICON_SVG = ${JSON.stringify(iconSvg)};
export const PNG_ICONS: Record<string, string> = ${JSON.stringify(pngs)};
`;

await mkdir(join(root, "src/ui/generated"), { recursive: true });
await writeFile(join(root, "src/ui/generated/bundle.ts"), out);

const gz = (s) => gzipSync(s, { level: 9 }).length;
const weight = gz(clientJs) + gz(clientCss);
const kb = (n) => (n / 1024).toFixed(1);
console.log(
  `client: js ${kb(clientJs.length)} KB (${kb(gz(clientJs))} KB gz), css ${kb(clientCss.length)} KB (${kb(gz(clientCss))} KB gz), build ${buildId}`,
);
if (process.argv.includes("--check") && weight > BUDGET_BYTES) {
  console.error(`Compressed page weight ${weight} B is over the ${BUDGET_BYTES} B budget`);
  process.exit(1);
}
